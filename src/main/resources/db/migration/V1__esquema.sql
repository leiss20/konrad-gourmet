CREATE TABLE Usuario (
  id_usuario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL,
  apellido varchar(100),
  email varchar(150) UNIQUE NOT NULL,
  password_hash varchar(255) NOT NULL,
  activo boolean DEFAULT true,
  id_rol int NOT NULL,
  id_sucursal int,
  fecha_creacion timestamp DEFAULT (now())
);

CREATE TABLE Rol (
  id_rol INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(50) UNIQUE NOT NULL,
  descripcion varchar(200)
);

CREATE TABLE Sucursal (
  id_sucursal INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(100) NOT NULL,
  direccion varchar(200),
  activo boolean DEFAULT true
);

CREATE TABLE Categoria (
  id_categoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(80) UNIQUE NOT NULL,
  descripcion varchar(200)
);

CREATE TABLE Producto (
  id_producto INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(120) NOT NULL,
  id_categoria int NOT NULL,
  id_unidad int NOT NULL,
  activo boolean DEFAULT true
);

CREATE TABLE Unidad (
  id_unidad INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(30) UNIQUE NOT NULL,
  abreviatura varchar(10)
);

CREATE TABLE Marca (
  id_marca INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(80) UNIQUE NOT NULL
);

CREATE TABLE Plato (
  id_plato INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(120) NOT NULL,
  precio_venta decimal(10,2) NOT NULL,
  id_sucursal int NOT NULL,
  activo boolean DEFAULT true,
  fecha_creacion timestamp DEFAULT (now())
);

CREATE TABLE Plato_Ingrediente (
  id_plato int NOT NULL,
  id_producto int NOT NULL,
  cantidad decimal(10,3) NOT NULL,
  id_unidad int NOT NULL,
  PRIMARY KEY (id_plato, id_producto)
);

CREATE TABLE Pedido (
  id_pedido INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_mesa int NOT NULL,
  id_sucursal int NOT NULL,
  id_mesero int NOT NULL,
  fecha_hora timestamp DEFAULT (now()),
  estado varchar(30) DEFAULT 'Registrado'
);

CREATE TABLE Pedido_Detalle (
  id_pedido_detalle INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido int NOT NULL,
  id_plato int NOT NULL,
  cantidad int NOT NULL,
  precio_unitario decimal(10,2)
);

CREATE TABLE Inventario (
  id_inventario INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_sucursal int NOT NULL,
  id_producto int NOT NULL,
  cantidad_actual decimal(12,3) NOT NULL,
  cantidad_referencia decimal(12,3) NOT NULL,
  ultima_actualizacion timestamp
);

CREATE TABLE Solicitud (
  id_solicitud INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_solicitud varchar(20) UNIQUE,
  id_sucursal int NOT NULL,
  id_solicitante int NOT NULL,
  fecha_solicitud timestamp DEFAULT (now()),
  estado varchar(30) DEFAULT 'PENDIENTE'
);

CREATE TABLE Solicitud_Detalle (
  id_solicitud_detalle INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_solicitud int NOT NULL,
  id_producto int NOT NULL,
  id_marca int,
  cantidad decimal(10,3) NOT NULL,
  id_unidad int NOT NULL
);

CREATE TABLE Proveedor (
  id_proveedor INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre varchar(150) NOT NULL,
  email varchar(150),
  telefono varchar(30),
  activo boolean DEFAULT true
);

CREATE TABLE Cotizacion (
  id_cotizacion INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_proveedor int NOT NULL,
  fecha_envio timestamp DEFAULT (now()),
  fecha_maxima_plazo date,
  estado varchar(30) DEFAULT 'ENVIADA',
  valor_total_proveedor decimal(12,2),
  valor_total_ministerio decimal(12,2)
);

CREATE TABLE Cotizacion_Detalle (
  id_cotizacion_detalle INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cotizacion int NOT NULL,
  id_solicitud_detalle int,
  id_producto int NOT NULL,
  id_unidad int NOT NULL,
  cantidad decimal(10,3),
  precio_unitario decimal(12,2),
  precio_ministerio decimal(12,2)
);

CREATE TABLE Orden_Compra (
  id_orden INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_orden varchar(20) UNIQUE,
  id_cotizacion int NOT NULL,
  id_proveedor int NOT NULL,
  fecha_generacion timestamp DEFAULT (now()),
  estado varchar(30) DEFAULT 'Generada',
  total decimal(12,2)
);

CREATE TABLE Orden_Compra_Detalle (
  id_orden_detalle INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_orden int NOT NULL,
  id_producto int NOT NULL,
  id_unidad int NOT NULL,
  cantidad decimal(10,3) NOT NULL,
  precio_unitario decimal(12,2) NOT NULL,
  subtotal decimal(12,2)
);

CREATE TABLE Auditoria (
  id_auditoria INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_usuario int,
  accion varchar(50),
  tabla_afectada varchar(50),
  registro_id int,
  fecha_hora timestamp DEFAULT (now()),
  detalle text
);

CREATE TABLE Log_Error (
  id_log INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha_hora timestamp DEFAULT (now()),
  modulo varchar(80),
  mensaje text,
  stack_trace text
);

